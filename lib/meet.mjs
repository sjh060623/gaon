export function rankResults(results,objective='fair',limit=120){
 return results.filter(r=>r.routes.length>1&&r.routes.every(t=>Number.isFinite(t.minutes)&&t.minutes>0&&t.minutes<=limit)).map(r=>{
  const times=r.routes.map(t=>t.minutes),max=Math.max(...times),min=Math.min(...times),avg=times.reduce((a,b)=>a+b,0)/times.length,spread=max-min;
  const score=objective==='fast'?max*.65+avg*.30+spread*.05:spread;
  return {...r,max,min,avg:Math.round(avg),spread,score};
 }).sort((a,b)=>a.score-b.score||a.max-b.max||a.place.id.localeCompare(b.place.id));
}
